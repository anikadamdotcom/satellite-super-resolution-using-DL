"""Shared four-band preprocessing, checkpoint validation and tiled inference."""
import numpy as np
import torch
import torch.nn.functional as F
from pathlib import Path

BAND_ORDER = ["B02", "B03", "B04", "B08"]
NORMALIZATION = 10000.0


def validate_image(image):
    image = np.asarray(image)
    if image.ndim != 3 or image.shape[2] != 4 or min(image.shape[:2]) < 1:
        raise ValueError("Expected a non-empty H x W x 4 image in B02,B03,B04,B08 order.")
    if image.dtype.kind not in "uif" or not np.isfinite(image).all() or image.min() < 0 or image.max() > 65535:
        raise ValueError("Band values must be finite and between 0 and 65535.")
    return image


def extract_features(image):
    """Eight channels; red/NIR contrast is NOT NDBI (which needs SWIR)."""
    bands = validate_image(image).astype(np.float32) / NORMALIZATION
    blue, green, red, nir = np.moveaxis(bands, -1, 0)
    ndvi = (nir - red) / (nir + red + 1e-6)
    ndwi = (green - nir) / (green + nir + 1e-6)
    red_nir = -ndvi
    lum = bands[..., :3].mean(axis=-1)
    gy = np.gradient(lum, axis=0) if lum.shape[0] > 1 else np.zeros_like(lum)
    gx = np.gradient(lum, axis=1) if lum.shape[1] > 1 else np.zeros_like(lum)
    grad = np.hypot(gx, gy)
    grad /= grad.max() + 1e-6
    features = np.concatenate([bands, np.stack([ndvi, ndwi, red_nir, grad], -1)], -1)
    return features.astype(np.float32), dict(b02=blue, b03=green, b04=red, b08=nir,
                                           ndvi=ndvi, ndwi=ndwi, red_nir=red_nir,
                                           grad=grad, lum=lum)


def read_checkpoint(path, task):
    if not Path(path).is_file() or Path(path).stat().st_size > 256*1024*1024:
        raise ValueError("Checkpoint must be an existing file no larger than 256 MB")
    checkpoint = torch.load(path, map_location="cpu", weights_only=True)
    if not isinstance(checkpoint, dict) or checkpoint.get("task") != task:
        raise ValueError(f"Expected a {task} checkpoint generated by train.py.")
    if checkpoint.get("band_order") != BAND_ORDER or checkpoint.get("normalization") != NORMALIZATION:
        raise ValueError("Checkpoint band order or reflectance normalization is incompatible.")
    if checkpoint.get("format_version") != 1:
        raise ValueError("Unsupported checkpoint version.")
    config = checkpoint.get("model_config", {})
    if not isinstance(config, dict):
        raise ValueError("Invalid checkpoint architecture configuration")
    if task == "sr" and (config.get("n_colors") != 4 or config.get("scale") != 2):
        raise ValueError("SR checkpoints must have four channels and a 2x scale.")
    if task == "segmentation" and (config.get("in_channels") != 8 or config.get("num_classes") != 5):
        raise ValueError("Segmentation checkpoints must have eight feature channels and five classes.")
    allowed = {"n_colors", "scale", "n_feats", "n_resgroups", "n_resblocks", "residual"} if task == "sr" else {"in_channels", "num_classes"}
    if set(config) - allowed:
        raise ValueError("Checkpoint contains unsupported architecture options")
    if task == "sr":
        for key, maximum in (("n_feats", 128), ("n_resgroups", 20), ("n_resblocks", 50)):
            value = config.get(key)
            if type(value) is not int or not 1 <= value <= maximum:
                raise ValueError(f"Invalid checkpoint option: {key}")
        if config["n_feats"]**2 * config["n_resgroups"] * config["n_resblocks"] > 2_000_000:
            raise ValueError("Checkpoint architecture exceeds the inference memory budget")
        if type(config.get("residual", False)) is not bool:
            raise ValueError("residual must be boolean")
    state = checkpoint.get("state_dict")
    if not isinstance(state, dict) or not state or any(not isinstance(v, torch.Tensor) or not torch.isfinite(v).all() for v in state.values()):
        raise ValueError("Checkpoint tensors are missing or non-finite")
    return checkpoint


@torch.inference_mode()
def tiled_predict(model, chw, device, scale=1, tile_size=128, halo=40, min_size=1, alignment=1):
    """Bound accelerator memory. Halo reduces seams; RCAN attention is tile-local."""
    if any(type(v) is not int for v in (tile_size, halo, scale, min_size, alignment)) or tile_size < 1 or halo < 0 or min(scale, min_size, alignment) < 1:
        raise ValueError("Invalid tile, halo, scale, padding or alignment configuration")
    if chw.ndim != 3 or min(chw.shape) < 1 or not np.isfinite(chw).all():
        raise ValueError("Tiled input must be a finite non-empty CHW array")
    _, h, w = chw.shape
    result = None
    for y in range(0, h, tile_size):
        for x in range(0, w, tile_size):
            y1, x1 = min(y + tile_size, h), min(x + tile_size, w)
            top, left = max(0, y - halo), max(0, x - halo)
            bottom, right = min(h, y1 + halo), min(w, x1 + halo)
            # U-Net's pooling grid must have the same origin in every tile.
            top, left = top//alignment*alignment, left//alignment*alignment
            bottom = min(h, ((bottom+alignment-1)//alignment)*alignment)
            right = min(w, ((right+alignment-1)//alignment)*alignment)
            tile = torch.from_numpy(np.ascontiguousarray(chw[:, top:bottom, left:right]))[None].to(device)
            th, tw = tile.shape[-2:]
            tile = F.pad(tile, (0, max(0, min_size - tw), 0, max(0, min_size - th)), mode="replicate")
            out = model(tile)[0].float().cpu().numpy()
            if out.ndim != 3 or out.shape[1:] != (tile.shape[2]*scale, tile.shape[3]*scale) or not np.isfinite(out).all():
                raise ValueError("Model returned non-finite pixels or an incorrect output shape")
            if result is not None and out.shape[0] != result.shape[0]:
                raise ValueError("Model output channels changed between tiles")
            if result is None:
                result = np.empty((out.shape[0], h * scale, w * scale), dtype=np.float32)
            sy, sx = (y - top) * scale, (x - left) * scale
            result[:, y*scale:y1*scale, x*scale:x1*scale] = out[:, sy:sy+(y1-y)*scale, sx:sx+(x1-x)*scale]
    return result
